"""
make_prompt_appendix.py - write report/appendix_prompts.md from experiment_config.py, so the
prompts printed in the report are exactly the ones the runs used.

Run:  python report/make_prompt_appendix.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import experiment_config as cfg  # noqa: E402

EXAMPLE_PROJECT = 225


def full_prompt(version: str) -> tuple[str, str]:
    cfg.PROMPT_VERSION = version
    cfg.TASK_TEXT = cfg.TASK_TEXTS[version]
    cfg.TASK_TEXT_ONCE = False      # show the v1-v3 layout: task text under every building
    meta = cfg.load_metadata().set_index("project_index")
    prefix = "\n\n".join(cfg.build_prefix())
    building = cfg.build_building_prompt(cfg.format_building(meta.loc[EXAMPLE_PROJECT]))
    return prefix, building


def fence(text: str) -> str:
    return "````text\n" + text + "\n````"


def main():
    prefix, b3 = full_prompt("v3")
    lines = [
        "# Appendix: prompts",
        "",
        "Generated by `report/make_prompt_appendix.py` from `experiment_config.py`.",
        "",
        "Each request is: system prompt, then the shared context (identical for every building), "
        "then the building block (its features, followed by the task text). In the subagent runs, "
        "one task file holds the shared context once and 48–49 building blocks. For v4 the task text "
        "is also written once per task file, after the glossary, and a building block holds only the features.",
        "",
        "## A. System prompt",
        "",
        fence(cfg.SYSTEM_PROMPT),
        "",
        "## B. Shared context (same in v1, v2 and v3)",
        "",
        "The glossary has one line per feature in `references/data_glossary_LLM.xlsx`.",
        "",
        fence(prefix),
        "",
        "## C. Task text v1 (baseline)",
        "",
        fence(cfg.TASK_TEXT_V1),
        "",
        "## D. Task text v2",
        "",
        fence(cfg.TASK_TEXT_V2),
        "",
        "## E. Task text v3",
        "",
        "Reference values come from `references/envelope_intensities_sources.md` (sources and "
        "conversions listed there).",
        "",
        fence(cfg.TASK_TEXTS["v3"]),
        "",
        "## F. Task text v4 (weighted evidence; best held-out result)",
        "",
        "Weighted evidence: the v3 take-off (A) and a benchmark by primary use (B), combined with equal "
        "weights. Benchmarks come from `results/benchmarks_dev.json` (cleaned development set); the "
        "literature facts are documented in `references/feature_keyed_facts.md`.",
        "",
        fence(cfg.TASK_TEXTS["v4"]),
        "",
        "## G. Task text v5 (answer-fitted, final enclosure prompt)",
        "",
        "In-sample by design: the calibration factors K and the benchmarks were fitted on the reference values of the "
        "262 cleaned buildings (`analysis/fit_v5_tables.py`, `results/v5_tables.json`), and the literature passages "
        "were selected because they agree with those values (`references/answer_guided_passages.md`).",
        "",
        fence(cfg.TASK_TEXTS["v5"]),
        "",
        "## H. Task text wb5 (whole building, A-C, answer-fitted)",
        "",
        "In-sample by design (`analysis/fit_wb_tables.py`, `results/wb_tables.json`).",
        "",
        fence(cfg.TASK_TEXTS["wb5"]),
        "",
        f"## I. Example building block, v3 (project-{EXAMPLE_PROJECT})",
        "",
        fence(b3),
        "",
        "## J. Subagent instructions (template)",
        "",
        "Rendered per task by `subagent_runs.py prepare` into "
        "`results/<run>/subagent/tasks/<task>.instructions.txt`.",
        "",
        fence(cfg.SUBAGENT_INSTRUCTIONS),
        "",
    ]
    out = ROOT / "report" / "appendix_prompts.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Saved {out}")

    # the deliverable: the final prompt on its own
    cfg.PROMPT_VERSION = "v5"
    cfg.TASK_TEXT = cfg.TASK_TEXTS["v5"]
    cfg.TASK_TEXT_ONCE = False
    meta = cfg.load_metadata().set_index("project_index")
    example = cfg.format_building(meta.loc[EXAMPLE_PROJECT])
    final = [
        "# Final prompt: LLM estimate of enclosure embodied carbon (A1-A3)",
        "",
        "CEE226 Group 8. Generated by `report/make_prompt_appendix.py` from `experiment_config.py` (prompt v5).",
        "",
        "| Target | Prompt | Within +/-20% of the reference LCA |",
        "|---|---|---|",
        "| Enclosure A1-A3 per m2 floor | v5 (this file) | 35.6% of 292 buildings; 38.5% after 30 outliers are removed |",
        "| Whole building A-C per m2 floor | wb5 (below) | 53.4% of 292 buildings (course reference results: 34-46%) |",
        "",
        "Both prompts are fitted to the reference data, as the course instructed, so these numbers are in-sample. "
        "With its benchmark fitted on a development set only, the same structure (v4) covers 35.2% of 88 held-out buildings. "
        "Model: Claude Opus 5.5, medium reasoning effort. The estimate is the midpoint of the returned range, averaged over 3 runs (whole building: 1 run).",
        "",
        "## How to assemble a request",
        "",
        "1. System prompt (section A).",
        "2. Shared context: the glossary of the 48 features (one line per feature from `references/data_glossary_LLM.xlsx`; "
        "see `appendix_prompts.md`, section B), then the task text (section B below).",
        "3. The building's features, one `field: value` line per non-empty feature (example in section C).",
        "",
        "## A. System prompt",
        "",
        fence(cfg.SYSTEM_PROMPT),
        "",
        "## B. Task text (v5)",
        "",
        fence(cfg.TASK_TEXTS["v5"]),
        "",
        f"## C. Example building (project-{EXAMPLE_PROJECT})",
        "",
        fence(example),
        "",
        "## D. Whole-building variant (wb5, stages A-C)",
        "",
        fence(cfg.TASK_TEXTS["wb5"]),
        "",
    ]
    out2 = ROOT / "report" / "final_prompt.md"
    out2.write_text("\n".join(final), encoding="utf-8")
    print(f"Saved {out2}")


if __name__ == "__main__":
    main()
