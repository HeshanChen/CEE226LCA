"""
make_prompt_appendix.py - write report/appendix_prompts.md from experiment_config.py, so the
prompts printed in the report are exactly the ones the runs used.

Run:  python report/make_prompt_appendix.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import experiment_config as cfg  # noqa: E402

EXAMPLE_PROJECT = 225


def full_prompt(version: str) -> tuple[str, str]:
    cfg.PROMPT_VERSION = version
    cfg.TASK_TEXT = cfg.TASK_TEXTS[version]
    meta = cfg.load_metadata().set_index("project_index")
    prefix = "\n\n".join(cfg.build_prefix())
    building = cfg.build_building_prompt(cfg.format_building(meta.loc[EXAMPLE_PROJECT]))
    return prefix, building


def fence(text: str) -> str:
    return "````text\n" + text + "\n````"


def main():
    prefix, b2 = full_prompt("v2")
    lines = [
        "# Appendix: prompts",
        "",
        "Generated by `report/make_prompt_appendix.py` from `experiment_config.py`.",
        "",
        "Each request is: system prompt, then the shared context (identical for every building), "
        "then the building block (its features, followed by the task text). In the subagent runs, "
        "one task file holds the shared context once and 48–49 building blocks.",
        "",
        "## A. System prompt",
        "",
        fence(cfg.SYSTEM_PROMPT),
        "",
        "## B. Shared context (same in v1 and v2)",
        "",
        "The glossary has one line per feature in `references/data_glossary_LLM.xlsx`.",
        "",
        fence(prefix),
        "",
        "## C. Task text v1 (baseline)",
        "",
        fence(cfg.TASK_TEXT_V1),
        "",
        "## D. Task text v2 (final prompt)",
        "",
        fence(cfg.TASK_TEXT_V2),
        "",
        f"## E. Example building block, v2 (project-{EXAMPLE_PROJECT})",
        "",
        fence(b2),
        "",
        "## F. Subagent instructions (template)",
        "",
        "Rendered per task by `subagent_runs.py prepare` into "
        "`results/<run>/subagent/tasks/<task>.instructions.txt`.",
        "",
        fence(cfg.SUBAGENT_INSTRUCTIONS),
        "",
    ]
    out = ROOT / "report" / "appendix_prompts.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Saved {out}")


if __name__ == "__main__":
    main()
